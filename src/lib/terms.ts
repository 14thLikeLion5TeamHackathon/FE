/**
 * 온보딩 약관 전문.
 *
 * 화면이 아니라 여기에 두는 이유는 **법정 고지 문구라 문구 자체가 계약이기 때문이다.**
 * JSX 사이에 흩어 놓으면 항목을 고칠 때 어느 화면을 봐야 하는지 알 수 없고,
 * 마이페이지에서 같은 전문을 다시 보여줄 때 두 벌이 갈라진다.
 *
 * 항목 순서·필수 여부·문구는 임의로 바꾸지 말 것. 바꾸려면 법무 확인이 먼저다.
 * 특히 `required`는 화면의 가입 버튼 활성 조건과 직결된다 — 선택 약관을 필수로 올리면
 * 동의를 강제하는 게 되어 개인정보보호법 위반이다.
 */

/** 약관 하나. `sections`는 고지에 반드시 들어가야 하는 항목들이라 순서대로 그대로 보여준다. */
export type Term = {
  id: TermId;
  title: string;
  /** 필수 동의 여부. 가입 버튼 활성 조건이 이 값으로 갈린다. */
  required: boolean;
  /**
   * 제목 옆 배지. 일반 동의와 법적 성격이 다르다는 걸 카드에서 바로 알려야 하는 항목들이다
   * (민감정보·국외이전·제3자 제공은 각각 별도 조항의 동의 대상이다).
   */
  badge?: string;
  /** 카드에 접힌 상태로 보이는 한 줄 요약. 전문은 `sections`. */
  summary?: string;
  sections: { label: string; body: string }[];
};

